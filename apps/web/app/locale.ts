export const catalog: Record<Locale, Record<string, string>> = { en: {}, th: thaiMessages };

export function resolveLocale(value: string): Locale {
  return localeOptions.find(option => option.id === value)?.id ?? "en";
}

export function translate(locale: Locale, message: string): string {
  const messages = catalog[locale];
  return Object.hasOwn(messages, message) ? messages[message] : message;
}
